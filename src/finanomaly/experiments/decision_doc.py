"""Generate docs/PROMOTION_DECISION.md from logged numbers (no hand-edited values)."""

from __future__ import annotations

import json

from finanomaly.config import ROOT, Config

CHECK_LABELS = {
    "recall_vs_reference": "Validation recall at least reference (production model or baseline)",
    "recall_vs_best_baseline": "Validation recall at least best rule baseline",
    "false_alarm_within_budget": "False alarm rate within budget (plus tolerance)",
    "seed_spread_acceptable": "Seed spread of recall acceptable",
    "explanations_available": "Explanations available and consistent",
    "serving_contract": "Serving contract test passes",
}


def _f(x: float | None, nd: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def write_decision_doc(cfg: Config) -> str:
    res = cfg.path("results")
    dec = json.loads((res / "promotion_decision.json").read_text())
    reg = json.loads((res / "registration.json").read_text())
    base = json.loads((res / "baselines_validation.json").read_text())
    lines = ["# Promotion decision", ""]
    lines.append(
        "Generated by `finanomaly promote` from MLflow and `results/`. Selection uses validation "
        "results only (models fit before 2015, evaluated on 2015 to 2018). Test-period results "
        "appear at the end, after the decision."
    )
    lines += ["", "## Reference: rule baselines on validation", ""]
    lines += [
        "| Baseline | Event recall | False alarm episodes per year | Average precision |",
        "|---|---|---|---|",
    ]
    for k, v in base.items():
        r = v["validation"]
        lines.append(
            f"| {k} | {_f(r['event_recall'])} | {_f(r['false_alarm_rate'], 2)} | "
            f"{_f(r['average_precision'])} |"
        )
    lines += ["", f"Best baseline validation recall (reference): {_f(dec['baseline_recall'])}.", ""]
    lines += ["## Candidates (staging alias)", ""]
    lines += [
        "| Model | Version | Config | Val recall | Val FA/yr | Val AP | Recall std (5 seeds) | "
        "Passes gate |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in dec["results"]:
        c = r["candidate"]
        cfg_idx = reg[c["family"]]["config_idx"]
        lines.append(
            f"| {c['name']} | {c['version']} | {cfg_idx} | {_f(c['recall'])} | "
            f"{_f(c['fa_rate'], 2)} | {_f(c['ap'])} | {_f(c['recall_std'])} | "
            f"{'yes' if r['passes'] else 'no'} |"
        )
    lines += ["", "## Criteria", ""]
    names = [r["candidate"]["name"] for r in dec["results"]]
    lines.append("| Criterion | " + " | ".join(names) + " |")
    lines.append("|---|" + "---|" * len(names))
    for key, label in CHECK_LABELS.items():
        cells = ["met" if r["checks"][key] else "not met" for r in dec["results"]]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += ["", "## Decision", ""]
    champ = dec["champion"]
    if champ is None:
        lines.append("No candidate met all criteria; no model was promoted.")
    else:
        lines.append(
            f"**Promoted to production: {champ['name']} version {champ['version']}.** Among the "
            "candidates that met every criterion it had the highest validation event recall "
            f"({_f(champ['recall'])}), with ties broken by lower false alarm rate "
            f"({_f(champ['fa_rate'], 2)} per year) and then higher validation average precision "
            f"({_f(champ['ap'])})."
        )
        lines += ["", "Models not chosen:", ""]
        for r in dec["results"]:
            c = r["candidate"]
            if c["name"] == champ["name"]:
                continue
            if not r["passes"]:
                failed = [CHECK_LABELS[k] for k, ok in r["checks"].items() if not ok]
                lines.append(f"* {c['name']}: failed {', '.join(failed)}.")
            else:
                lines.append(
                    f"* {c['name']}: met all criteria but ranked lower (recall {_f(c['recall'])}, "
                    f"false alarm rate {_f(c['fa_rate'], 2)}, average precision {_f(c['ap'])})."
                )
    lines += [
        "",
        "With three validation events recall takes only the values 0, 1/3, 2/3 and 1, so ties are "
        "common and the ranking rests on the tie-breaks. The deployed model is the refit on all "
        "pre-2019 data; the criteria use the validation-stage fit (data before 2015).",
    ]
    ts = res / "test_summary.json"
    lines += ["", "## Test period results (reported after the decision)", ""]
    if ts.exists():
        t = json.loads(ts.read_text())
        lines += [
            "| Entry | Events detected | Event recall | False alarm episodes per year | AP |",
            "|---|---|---|---|---|",
        ]
        for e in t["entries"]:
            lines.append(
                f"| {e['label']} | {e['n_detected']} of {e['n_events']} | {_f(e['event_recall'])}"
                f" | {_f(e['false_alarm_rate'], 2)} | {_f(e['average_precision'])} |"
            )
        if champ is not None:
            lines += ["", f"Per-event outcome of the champion ({champ['name']}):", ""]
            lines += ["| Event | Detected | Delay (trading days) |", "|---|---|---|"]
            for e in t["champion_events"]:
                d = e["delay_days"]
                lines.append(
                    f"| {e['event']} | {'yes' if e['detected'] else 'no'} | "
                    f"{'n/a' if d is None else d} |"
                )
        lines += ["", t.get("note", "")]
    else:
        lines.append("Not yet evaluated.")
    text = "\n".join(lines) + "\n"
    (ROOT / "docs" / "PROMOTION_DECISION.md").write_text(text, encoding="utf-8")
    return text
